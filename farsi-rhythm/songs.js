const SONGS = (() => {
  const toFa = s => s.replace(/ي/g, 'ی').replace(/ك/g, 'ک').trim();
  const songs = [];
  let cur = null, section = '';
  for (const raw of SONGS_RAW.split('\n')) {
    const line = raw.trim();
    if (!line) continue;
    if (line[0] === '@') {
      const [lesson, fa, ar, style] = line.slice(1).split('|');
      cur = { id: songs.length, lesson: +lesson, fa: toFa(fa), ar: ar.trim(), style: style.trim(), lines: [] };
      songs.push(cur);
    } else if (line[0] === '[') {
      section = line;
    } else {
      const [fa, ar] = line.split('|');
      cur.lines.push({ i: cur.lines.length, section, fa: toFa(fa), ar: (ar || '').trim() });
      section = '';
    }
  }
  return songs;
})();

if (typeof module !== 'undefined') module.exports = SONGS;
