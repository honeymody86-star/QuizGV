const COURSE = (() => {
  const HARAKAT = /[ً-ْٰ]/g;
  const toFa = s => s.replace(/ي/g, 'ی').replace(/ك/g, 'ک').trim();
  const lessons = [], words = [], sentences = [];
  let cur = null;
  for (const raw of COURSE_RAW.split('\n')) {
    const line = raw.trim();
    if (!line) continue;
    if (line[0] === '#') {
      const [title, icon] = line.slice(1).split('|');
      cur = { id: lessons.length, title: title.trim(), icon: (icon || '').trim(), words: [], sentences: [] };
      lessons.push(cur);
    } else if (line[0] === '>') {
      const [fa, ar, icons, idx] = line.slice(1).split('|');
      const s = {
        id: sentences.length, lesson: cur.id, fa: toFa(fa), ar: ar.trim(), icon: (icons || '').trim(),
        words: (idx || '').split(',').filter(Boolean).map(i => cur.words[+i])
      };
      sentences.push(s); cur.sentences.push(s.id);
      s.words.forEach(wid => words[wid].sentences.push(s.id));
    } else {
      const [voc, ar, icon] = line.split('|');
      const w = {
        id: words.length, lesson: cur.id, voc: toFa(voc), fa: toFa(voc).replace(HARAKAT, ''),
        ar: ar.trim(), icon: (icon || '').trim(), sentences: []
      };
      words.push(w); cur.words.push(w.id);
    }
  }
  return { lessons, words, sentences };
})();

