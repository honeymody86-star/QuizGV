/* استخراج JSON من رد نموذج (قد يحتوي ```json أو نصًا زائدًا) */
window.extractJSON = function (text) {
  if (!text) throw new Error('الرد فارغ');
  let t = String(text).trim();
  t = t.replace(/^﻿/, '');
  const fence = t.match(/```(?:json)?\s*([\s\S]*?)```/i);
  if (fence) t = fence[1].trim();
  const start = t.indexOf('{');
  const end = t.lastIndexOf('}');
  if (start < 0 || end < 0) throw new Error('لم أجد كائن JSON في الرد. تأكد من نسخ الرد كاملًا.');
  t = t.slice(start, end + 1);
  try { return JSON.parse(t); } catch (e) {
    // إصلاحات شائعة: فواصل زائدة، علامات اقتباس ذكية
    const fixed = t
      .replace(/[“”]/g, '"')
      .replace(/,\s*([}\]])/g, '$1')
      .replace(/\n/g, ' ');
    return JSON.parse(fixed);
  }
};
