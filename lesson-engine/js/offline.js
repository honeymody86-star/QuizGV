  function keywords(text, n) {
    const freq = {};
    words(text).forEach(w => {
      const k = w.replace(/^(وال|بال|فال|كال|ال|لل)/, '');
      if (STOP.has(w) || STOP.has(k) || k.length < 3) return;
      freq[w] = (freq[w] || 0) + 1;
    });
    return Object.entries(freq).sort((a, b) => b[1] - a[1] || b[0].length - a[0].length).slice(0, n).map(e => e[0]);
  }
